use super::RawDep;

fn quoted(rest: &str) -> Option<&str> {
    let rest = rest.trim();
    let inner = rest.strip_prefix('"')?;
    inner.split('"').next()
}

/// `Cargo.lock`: hanya paket dari registry crates.io (ada `source = "registry+..."`/`"sparse+..."`);
/// anggota workspace dan sumber git/path dilewati. Baris = baris `name = ...`.
pub fn parse(text: &str) -> Result<Vec<RawDep>, String> {
    let mut out = Vec::new();
    let mut in_package = false;
    let mut name: Option<(String, u32)> = None;
    let mut version: Option<String> = None;
    let mut source: Option<String> = None;
    let mut saw_package = false;

    let flush = |name: &mut Option<(String, u32)>,
                 version: &mut Option<String>,
                 source: &mut Option<String>,
                 out: &mut Vec<RawDep>| {
        if let (Some((n, line)), Some(v), Some(s)) = (name.take(), version.take(), source.take()) {
            let crates_io = s.contains("crates.io");
            if crates_io && (s.starts_with("registry+") || s.starts_with("sparse+")) {
                out.push(RawDep {
                    name: n,
                    version: v,
                    dev: false,
                    line,
                });
            }
        }
        *name = None;
        *version = None;
        *source = None;
    };

    for (idx, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.starts_with('[') {
            flush(&mut name, &mut version, &mut source, &mut out);
            in_package = line == "[[package]]";
            saw_package |= in_package;
            continue;
        }
        if !in_package {
            continue;
        }
        if let Some(v) = line.strip_prefix("name =") {
            name = quoted(v).map(|n| (n.to_string(), idx as u32 + 1));
        } else if let Some(v) = line.strip_prefix("version =") {
            version = quoted(v).map(str::to_string);
        } else if let Some(v) = line.strip_prefix("source =") {
            source = quoted(v).map(str::to_string);
        }
    }
    flush(&mut name, &mut version, &mut source, &mut out);
    if !saw_package && !text.trim().is_empty() && !text.contains("version =") {
        return Err("bukan Cargo.lock yang valid (tidak ada [[package]])".to_string());
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registry_packages_only() {
        let src = "# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"time\",\n]\n\n[[package]]\nname = \"time\"\nversion = \"0.1.43\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"abc\"\n\n[[package]]\nname = \"gitdep\"\nversion = \"1.0.0\"\nsource = \"git+https://example.com/x#abcd\"\n\n[[package]]\nname = \"sparse\"\nversion = \"2.0.0\"\nsource = \"sparse+https://index.crates.io/\"\n\n[[package]]\nname = \"alt\"\nversion = \"3.0.0\"\nsource = \"registry+https://internal.example/index\"\n";
        let d = parse(src).unwrap();
        let got: Vec<(&str, &str, u32)> = d
            .iter()
            .map(|d| (d.name.as_str(), d.version.as_str(), d.line))
            .collect();
        assert_eq!(got, [("time", "0.1.43", 12), ("sparse", "2.0.0", 23)]);
    }

    #[test]
    fn garbage_is_an_error_and_empty_is_fine() {
        assert!(parse("hello world\n").is_err());
        assert!(parse("").unwrap().is_empty());
        assert!(parse("version = 3\n").unwrap().is_empty());
    }
}
