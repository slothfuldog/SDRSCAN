// Writes assets/css/ui-colors.css from config/uiColors.ts. Run: npm run gen:ui-colors
import { writeFileSync } from 'node:fs'
import { UI_COLORS } from '../config/uiColors.ts'
import { generateUiColorsCss } from './ui-colors-css.ts'

